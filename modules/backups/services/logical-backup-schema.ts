import { z } from "zod"

const maybeString = z.string().nullable().optional()
const maybeNumber = z.number().nullable().optional()

export const logicalBackupPackSchema = z.object({
  kind: z.literal("oryx-logical-backup"),
  version: z.number().int().nonnegative(),
  exportedAt: z.string().min(1).optional(),
  source: z.enum(["supabase", "sqlite"]).optional(),
  checksumAlgorithm: z.literal("sha256").optional(),
  checksum: z.string().regex(/^[a-f0-9]{64}$/i).optional(),
  counts: z.record(z.string(), z.number()).optional(),
  tables: z.object({
    users: z.array(z.object({
      id: maybeString,
      name: maybeString,
      email: maybeString,
      role: maybeString,
      active: z.number().optional(),
      // Accepted on legacy v1 packs only — never written by v2+ exporters.
      passwordHash: maybeString,
      mustChangePassword: z.number().optional(),
      createdAt: maybeString,
      updatedAt: maybeString,
    }).passthrough()),
    clients: z.array(z.object({
      id: maybeString,
      name: maybeString,
      contactName: maybeString,
      phone: maybeString,
      email: maybeString,
      billingAddress: maybeString,
      notes: maybeString,
      accountCode: maybeString,
      active: z.number().optional(),
      createdAt: maybeString,
      updatedAt: maybeString,
    }).passthrough()),
    jobs: z.array(z.object({
      id: maybeString,
      drawingNumber: maybeString,
      itemType: maybeString,
      address: maybeString,
      typeOfWorks: maybeString,
      customTypeDescription: maybeString,
      clientCompany: maybeString,
      clientId: maybeString,
      requestedBy: maybeString,
      status: maybeString,
      designer: maybeString,
      quoteValue: maybeNumber,
      variationFees: maybeNumber,
      quoteReference: maybeString,
      dateCreated: maybeString,
      requiredByDate: maybeString,
      dateCompleted: maybeString,
      notes: maybeString,
      parentJobId: maybeString,
      revisionLetter: maybeString,
      updatedAt: maybeString,
    }).passthrough()),
    quotes: z.array(z.object({
      id: maybeString,
      quoteNumber: maybeString,
      clientId: maybeString,
      clientCompany: maybeString,
      contactName: maybeString,
      address: maybeString,
      description: maybeString,
      quoteValue: z.number().optional(),
      vatRate: maybeNumber,
      quoteDate: maybeString,
      expiryDate: maybeString,
      status: maybeString,
      notes: maybeString,
      createdBy: maybeString,
      createdAt: maybeString,
      updatedAt: maybeString,
    }).passthrough()),
  }),
}).passthrough()

export type LogicalBackupPackInput = z.infer<typeof logicalBackupPackSchema>
